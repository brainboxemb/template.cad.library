import json
from pathlib import Path
from tempfile import TemporaryDirectory
import unittest

from cad_library_pages.homepage import homepage_manifest, prepare_homepage


class HomepageTests(unittest.TestCase):
    def _root(self, text: str):
        tmp = TemporaryDirectory()
        root = Path(tmp.name)
        (root / "site").mkdir()
        (root / "site/home.yml").write_text(text, encoding="utf-8")
        self.addCleanup(tmp.cleanup)
        return root

    def test_prepare_generates_normalized_hugo_data(self):
        root = self._root(
            """schema: 1
blocks:
  - type: hero
    eyebrow: Library
    title: Generated home
    lead: Generated by Pages.
    actions:
      - label: Docs
        route: docs/
        primary: true
      - label: Project
        url: https://example.org/project/
  - type: catalogue
    title: Examples
    description: Generated models.
    section: examples
"""
        )
        site = root / "prepared-site"
        prepare_homepage(root, site)
        data = json.loads((site / "data/home.json").read_text(encoding="utf-8"))
        self.assertEqual(data["schema"], 1)
        self.assertEqual(data["blocks"][0]["actions"][0]["route"], "docs/")
        self.assertFalse(data["blocks"][0]["actions"][0]["external"])
        self.assertTrue(data["blocks"][0]["actions"][1]["external"])

    def test_destination_must_choose_route_or_url(self):
        root = self._root(
            """schema: 1
blocks:
  - type: hero
    eyebrow: Library
    title: Broken
    lead: Invalid destination.
    actions:
      - label: Invalid
        route: docs/
        url: https://example.org/
"""
        )
        with self.assertRaisesRegex(ValueError, "exactly one of route or url"):
            homepage_manifest(root)

    def test_unknown_block_type_fails_closed(self):
        root = self._root(
            """schema: 1
blocks:
  - type: handwritten-html
"""
        )
        with self.assertRaisesRegex(ValueError, "not supported"):
            homepage_manifest(root)


if __name__ == "__main__":
    unittest.main()
